"""Regenerate redistributable notices from the locked Cargo dependency graph.

Contributor tool only; no Python dependency in installed VEXA. Fetch dependencies
with Cargo first. Includes all target/build dependencies and MPL option-ext source.
"""
import json
from pathlib import Path
import shutil
import subprocess


def main():
    root = Path(__file__).resolve().parents[1]
    metadata = json.loads(subprocess.check_output(
        ["cargo", "metadata", "--locked", "--offline", "--format-version", "1"],
        cwd=root, encoding="utf-8"))
    packages = sorted((p for p in metadata["packages"] if p["source"]),
                      key=lambda p: (p["name"], p["version"]))
    table = ["# Third-party licenses", "",
             "Generated by `python tools/generate_notices.py` from locked Cargo metadata. "
             "Includes target-specific and build dependencies. No neural weights are bundled. "
             "MPL-2.0 option-ext source is included in the notices and binary distribution.", "",
             "| Crate | Version | License | Notices |", "| --- | --- | --- | --- |"]
    combined = ["VEXA THIRD-PARTY NOTICES\nVEXA itself is MIT licensed.\n"]
    for package in packages:
        name, version = package["name"], package["version"]
        origin = Path(package["manifest_path"]).parent
        destination = root / "third-party" / f"{name}-{version}"
        destination.mkdir(parents=True, exist_ok=True)
        attribution = (f"Crate: {name}\nVersion: {version}\n"
                       f"SPDX license declaration: {package['license']}\n"
                       f"Repository: {package['repository'] or ''}\n"
                       f"Authors: {', '.join(package['authors'])}\n"
                       f"Source: https://crates.io/crates/{name}/{version}\n")
        (destination / "ATTRIBUTION.txt").write_text(attribution, encoding="utf-8")
        combined.append(f"\n{'=' * 72}\n{attribution}")
        notices = [p for p in origin.iterdir() if p.is_file() and
                   p.name.upper().startswith(("LICENSE", "LICENCE", "COPYING", "NOTICE"))]
        license_file = package.get("license_file")
        if license_file:
            explicit = origin / license_file
            if explicit.is_file() and explicit not in notices:
                notices.append(explicit)
        if not package["license"] and not notices:
            raise RuntimeError(f"Missing license declaration and notices: {name} {version}")
        for notice in sorted(notices):
            shutil.copyfile(notice, destination / notice.name)
            combined.append(f"\n--- {notice.name} ---\n" + notice.read_text(encoding="utf-8", errors="strict"))
        if name == "option-ext":
            for source in [origin / "Cargo.toml", *sorted((origin / "src").rglob("*.rs"))]:
                relative = source.relative_to(origin)
                target = destination / relative
                target.parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(source, target)
                combined.append(f"\n--- MPL corresponding source: {relative.as_posix()} ---\n"
                                + source.read_text(encoding="utf-8"))
        table.append(f"| {name} | {version} | {package['license'] or 'see notices'} | "
                     f"[notices](third-party/{name}-{version}/) |")
    (root / "THIRD_PARTY_LICENSES.md").write_text("\n".join(table) + "\n", encoding="utf-8")
    (root / "THIRD_PARTY_LICENSES.txt").write_text("\n".join(combined) + "\n", encoding="utf-8")
    print(json.dumps({"dependencies": len(packages), "notices_bytes":
                      (root / "THIRD_PARTY_LICENSES.txt").stat().st_size}))


if __name__ == "__main__":
    main()
